"""Generate synthetic 3-axis accelerometer windows and train a tiny motion tree.

Run: python train_motion_model.py
The resulting CSV is synthetic training data, not measured human data.
"""
from pathlib import Path
import csv
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier, export_text
from sklearn.metrics import accuracy_score, classification_report

ROOT = Path(__file__).resolve().parent
CLASSES = ("Walking", "Running", "Resting")
FS, WINDOW_SECONDS = 25, 2
N = FS * WINDOW_SECONDS
FEATURES = ("std_x", "std_y", "std_z", "mag_std", "mag_mean", "crossings", "acf_peak")

def synth_window(label, rng):
    t = np.arange(N) / FS
    # Gravity is expressed in g. Synthetic gait has a dominant periodic component,
    # varying orientation, cadence, phase, and noise between windows.
    gravity = rng.normal(0, 1, 3)
    gravity *= 1.0 / max(np.linalg.norm(gravity), 1e-6)
    x = np.tile(gravity[:, None], (1, N))
    if label == "Walking":
        freq, amp, noise = rng.uniform(1.4, 2.2), rng.uniform(.10, .32), .045
    elif label == "Running":
        freq, amp, noise = rng.uniform(2.4, 3.6), rng.uniform(.35, .85), .11
    else:
        freq, amp, noise = 0, rng.uniform(0, .035), .012
    phase = rng.uniform(0, 2*np.pi)
    direction = rng.normal(size=3); direction /= np.linalg.norm(direction)
    if freq:
        wave = amp * np.sin(2*np.pi*freq*t + phase)
        # Secondary harmonic makes the pattern less perfectly sinusoidal.
        wave += .22*amp*np.sin(4*np.pi*freq*t + phase*.7)
        x += direction[:, None] * wave
    else:
        x += direction[:, None] * (amp*np.sin(2*np.pi*rng.uniform(.1,.6)*t+phase))
    x += rng.normal(0, noise, x.shape)
    # Small sensor placement/orientation variation.
    x *= rng.uniform(.92, 1.08)
    # Simulated MAX30102 heart rate. These broad, overlapping ranges are only
    # plausible demo values; activity/heart rate is not a reliable diagnosis.
    hr_center = {"Walking": 108, "Running": 148, "Resting": 72}[label]
    hr = float(np.clip(rng.normal(hr_center, {"Walking": 18, "Running": 22, "Resting": 12}[label]), 45, 205))
    return x.astype(np.float32), hr

def extract_features(x, hr=None):
    mag = np.sqrt(np.sum(x*x, axis=0))
    centered = mag - mag.mean()
    crossings = np.count_nonzero((centered[:-1] <= 0) & (centered[1:] > 0))
    denom = float(np.dot(centered, centered)) + 1e-9
    acf = [float(np.dot(centered[:-lag], centered[lag:]) / denom) for lag in range(5, 13)]
    # Heart rate is intentionally not a model input: MAX30102 pulse readings
    # are optional context and cannot replace an accelerometer for activity.
    return np.array([*x.std(axis=1), mag.std(), mag.mean(), crossings, max(acf)], dtype=np.float32)

def emit_header(model, path):
    tr = model.tree_
    left, right, feat, thresh, value = tr.children_left, tr.children_right, tr.feature, tr.threshold, tr.value
    classes = model.classes_.tolist()
    lines = ["// Generated by train_motion_model.py. Features: std_x/y/z, mag_std/mean, crossings, acf_peak.",
             "#pragma once", "#include <stdint.h>",
             f"#define MOTION_NODE_COUNT {tr.node_count}",
             f"#define MOTION_CLASS_COUNT {len(classes)}",
             "static const int16_t motion_left[MOTION_NODE_COUNT] = {" + ",".join(map(str,left)) + "};",
             "static const int16_t motion_right[MOTION_NODE_COUNT] = {" + ",".join(map(str,right)) + "};",
             "static const int8_t motion_feature[MOTION_NODE_COUNT] = {" + ",".join(map(str,feat)) + "};",
             "static const float motion_threshold[MOTION_NODE_COUNT] = {" + ",".join(f"{v:.7g}f" if "." in f"{v:.7g}" or "e" in f"{v:.7g}" else f"{v:.7g}.0f" for v in thresh) + "};"]
    preds = [int(classes[int(np.argmax(row[0]))]) for row in value]
    lines.append("static const uint8_t motion_prediction[MOTION_NODE_COUNT] = {" + ",".join(map(str,preds)) + "};")
    lines.append("static const char* const motion_labels[MOTION_CLASS_COUNT] = {" + ",".join('"'+CLASSES[int(c)]+'"' for c in classes) + "};")
    lines += ["static inline uint8_t predictMotion(const float* f) {", "  int n = 0;",
              "  while (motion_left[n] != -1) n = (f[motion_feature[n]] <= motion_threshold[n]) ? motion_left[n] : motion_right[n];",
              "  return motion_prediction[n];", "}"]
    path.write_text("\n".join(lines)+"\n", encoding="utf-8")

def main():
    rng = np.random.default_rng(20261010)
    X, y, raw = [], [], []
    for label, name in enumerate(CLASSES):
        for _ in range(1000):
            x, hr = synth_window(name, rng)
            X.append(extract_features(x, hr)); y.append(label); raw.append((name, x, hr))
    X, y = np.asarray(X), np.asarray(y)
    Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=.25, random_state=42, stratify=y)
    model = DecisionTreeClassifier(max_depth=5, min_samples_leaf=12, class_weight="balanced", random_state=42)
    model.fit(Xtr, ytr)
    yp = model.predict(Xte)
    with (ROOT/"synthetic_accelerometer.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f); w.writerow([f"{axis}_{i}" for axis in "xyz" for i in range(N)] + ["heart_rate_bpm", "label"])
        for name, x, hr in raw: w.writerow([*x.reshape(-1).tolist(), hr, name])
    emit_header(model, ROOT/"motion_model.h")
    report = ["# Synthetic motion classifier", "", f"Held-out accuracy: {accuracy_score(yte, yp):.3f}", "",
              "## Per-class metrics", "```", classification_report(yte, yp, target_names=CLASSES), "```", "",
              "## Learned tree", "```", export_text(model, feature_names=list(FEATURES)), "```", "",
              f"Model: {model.tree_.node_count} nodes, max depth {model.get_depth()}.",
              "Data are simulated; held-out scores measure synthetic consistency, not real-world performance."]
    (ROOT/"training_report.md").write_text("\n".join(report), encoding="utf-8")
    print("Accuracy:", round(accuracy_score(yte, yp), 3), "nodes:", model.tree_.node_count, "depth:", model.get_depth())
    print(classification_report(yte, yp, target_names=CLASSES))

if __name__ == "__main__": main()
